# NPC ID -> 模板常量 映射
NPC_PROMPT_MAP = {
    "sophia": SOPHIA_SYSTEM_PROMPT,
    "viktor": VIKTOR_SYSTEM_PROMPT,
    "aisha": AISHA_SYSTEM_PROMPT,
    "marcus": MARCUS_SYSTEM_PROMPT,
    "lin_ruoxi": LIN_RUOXI_SYSTEM_PROMPT,
    # chen_hao 仍在 prompt.py 的 CHEN_HAO_SYSTEM_PROMPT 中
}


def get_npc_system_prompt(agent_id: str, **state_vars) -> str:
    """
    获取 NPC 人格 Prompt 并注入运行时状态变量。

    参数:
      agent_id: NPC 标识（sophia/viktor/aisha/marcus/lin_ruoxi）
      **state_vars: 至少包含以下 5 个键：
        - stress: float 0-1
        - morale: float 0-1
        - trust_in_player: float 0-1
        - stage: str（survival/explore/build/climax）
        - recent_events: str

    返回:
      渲染后的 system prompt 字符串

    渲染引擎建议:
      使用 Jinja2:
          from jinja2 import Template
          return Template(template).render(**state_vars)
      （当前实现用 .format 兼容会失败——{{var}} 需 Jinja2）
    """
    template = NPC_PROMPT_MAP.get(agent_id)
    if template is None:
        raise KeyError(f"Unknown agent_id: {agent_id}, valid: {list(NPC_PROMPT_MAP.keys())}")
    # 推荐实现：Jinja2
    try:
        from jinja2 import Template
        return Template(template).render(**state_vars)
    except ImportError:
        # 退化方案：无 Jinja2 时手动替换
        result = template
        for key, val in state_vars.items():
            result = result.replace("{{" + key + "}}", str(val))
        return result
